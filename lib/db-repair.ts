/**
 * Проверка и починка автоинкремента id — общая для скрипта fix-blog-db.ts
 * и для страницы /admin/db-health.
 *
 * Проверяются ВСЕ таблицы схемы public, а не заданный список. Прошлая
 * версия смотрела только на девять известных таблиц, а сохранение статьи
 * пишет ещё и в таблицы связей — они в список не входили.
 */

import type { Sql } from 'postgres';

export type IdStatus = {
  table: string;
  type: string;
  nullable: boolean;
  default: string | null;
  identity: boolean;
  ok: boolean;
};

/** Состояние колонки id во всех таблицах, где она есть. */
export async function inspectIds(sql: Sql): Promise<IdStatus[]> {
  const rows = await sql`
    SELECT table_name, data_type, is_nullable, column_default, is_identity
    FROM information_schema.columns
    WHERE table_schema = 'public' AND column_name = 'id'
      AND table_name NOT LIKE '%backup%'
    ORDER BY table_name
  `;
  return rows.map((r: any) => {
    const identity = r.is_identity === 'YES';
    const numeric = /int|numeric/.test(r.data_type);
    return {
      table: r.table_name,
      type: r.data_type,
      nullable: r.is_nullable === 'YES',
      default: r.column_default,
      identity,
      // Числовой id без значения по умолчанию — INSERT без явного id упадёт
      ok: !numeric || Boolean(r.column_default) || identity,
    };
  });
}

/**
 * Чинит одну таблицу. Если старый счётчик от SERIAL жив — возвращает
 * DEFAULT на него (точное восстановление). Если счётчика нет — заводит
 * IDENTITY. В обоих случаях следующее значение ставится за максимальный id.
 */
export async function repairId(sql: Sql, table: string): Promise<void> {
  if (!/^[a-z_][a-z0-9_]*$/.test(table)) throw new Error(`Недопустимое имя таблицы: ${table}`);

  const [{ max }] = await sql.unsafe(`SELECT COALESCE(MAX(id), 0)::bigint AS max FROM ${table}`);
  const next = Number(max) + 1;
  const [owned] = await sql`SELECT pg_get_serial_sequence(${table}, 'id') AS seq`;

  await sql.unsafe(`ALTER TABLE ${table} ALTER COLUMN id SET NOT NULL`);

  if (owned?.seq) {
    // Важно не заводить рядом второй счётчик: при живом старом
    // pg_get_serial_sequence возвращает СТАРЫЙ, и новая запись получала
    // id = 1 — дубль. Проверено на тестовой базе.
    await sql.unsafe(`ALTER TABLE ${table} ALTER COLUMN id SET DEFAULT nextval('${owned.seq}'::regclass)`);
    await sql.unsafe(`SELECT setval('${owned.seq}'::regclass, ${next}, false)`);
  } else {
    await sql.unsafe(`ALTER TABLE ${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    await sql.unsafe(`ALTER TABLE ${table} ALTER COLUMN id RESTART WITH ${next}`);
  }
}

/** Какая база на самом деле подключена: хост и имя, без пароля. */
export async function whereAmI(sql: Sql): Promise<{ host: string; database: string }> {
  const [r] = await sql`SELECT current_database() AS db, inet_server_addr()::text AS ip`;
  let host = '';
  try {
    host = new URL(process.env.DATABASE_URL || process.env.DIRECT_URL || '').hostname;
  } catch { /* нет URL — покажем IP */ }
  return { host: host || r.ip || '?', database: r.db };
}
