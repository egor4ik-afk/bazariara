## Берикаоба — грузинский карнавал масок

У Грузии есть собственный праздник с масками и костюмами, и он намного старше Хэллоуина. Берикаоба — древний народный карнавал, который проводят весной. Участники, берики, надевают маски и шкуры, разыгрывают сценки и высмеивают злые силы, а сам праздник связан с плодородием и пробуждением природы.

Если Хэллоуин — праздник осени и страхов, то Берикаоба — праздник весны и смеха над тем, чего боятся.

## Как выбрать тыкву

Для фонаря и для еды подходят разные тыквы.

- **Для фонаря** берите круглую тыкву с ровными боками, плотной кожурой и крепким сухим хвостиком. Она должна устойчиво стоять. Вмятины и мягкие пятна — признак того, что тыква начнёт гнить уже через пару дней после вырезания.
- **Для еды** лучше небольшие сладкие сорта, например мускатная тыква. Спелая тыква тяжёлая для своего размера, а при постукивании звучит глухо.
- **Хранение.** Целая тыква спокойно лежит несколько недель в прохладном месте. Вырезанный фонарь простоит 3–5 дней, дольше — если держать его в прохладе и смазать срезы растительным маслом.

